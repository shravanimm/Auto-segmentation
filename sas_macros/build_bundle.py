"""
build_bundle.py - concatenates every segmentation macro into ONE file so it can be
uploaded to SAS Content in a single step.

Order = the %include order in autoseg_ucmacros/seg_compile.sas (macro definitions only).
Re-run after ANY change to a macro, then re-upload seg_all_macros_bundle.sas:
    python sas_macros/build_bundle.py
"""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
mac = os.path.join(here, "autoseg_ucmacros")
order = re.findall(r'%include "&_autoseg_ucmacros/([\w]+\.sas)";', open(os.path.join(mac, "seg_compile.sas"), encoding="utf-8").read())
order = [f for f in order if f != "seg_compile.sas"]   # the compile file only lists includes (its header comment mentions itself)
out = ["/* ============================================================================",
       "   seg_all_macros_bundle.sas  -  GENERATED by build_bundle.py - DO NOT EDIT HERE.",
       "   Every segmentation macro in one file (%d files). Edit the files in" % len(order),
       "   autoseg_ucmacros/ and re-run build_bundle.py. Usage:",
       "       filename bundle filesrvc folderpath=\"<folder>\" filename=\"seg_all_macros_bundle.sas\";",
       "       %include bundle;",
       "   ============================================================================ */", ""]
for f in order:
    body = open(os.path.join(mac, f), encoding="utf-8").read().rstrip() + "\n"
    out += ["/* >>>>>>>>>>>>>>>> %s <<<<<<<<<<<<<<<< */" % f, body]
out.append("%put NOTE: All segmentation macros compiled from seg_all_macros_bundle.sas;")
text = "\n".join(out)
open(os.path.join(here, "seg_all_macros_bundle.sas"), "w", encoding="utf-8", newline="\n").write(text)
print("files bundled:", len(order), "| %macro:", text.count("%macro "), "| %mend:", text.count("%mend"), "| size KB:", round(len(text.encode())/1024, 1))
